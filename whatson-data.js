/* ============================================================
   สถานะกิจกรรมตามวันที่ — ใช้ร่วม: whatson.html + around.html
   ทุกกิจกรรมมี start / end (YYYY-MM-DD, ค.ศ.) = ช่อง "วันเริ่ม / วันสิ้นสุด" ในหลังบ้าน
   (ไม่มี → อ่านจากข้อความ date ภาษาไทย เช่น "6 พ.ค. – 4 ก.ค. 2569")
   กำลังจัด = ยังไม่เลยวันสิ้นสุด (รวมที่ยังไม่เริ่ม) · ผ่านมา = เลยวันสิ้นสุดแล้ว
   → ย้ายหมวดเองอัตโนมัติเมื่อเปิดหน้าหลังวันสิ้นสุด (เวลาไทย) · ทดสอบวันอื่น: ?today=2026-06-20
   ============================================================ */
(function(){
  var MONTHS={'ม.ค.':1,'ก.พ.':2,'มี.ค.':3,'เม.ย.':4,'พ.ค.':5,'มิ.ย.':6,'ก.ค.':7,'ส.ค.':8,'ก.ย.':9,'ต.ค.':10,'พ.ย.':11,'ธ.ค.':12};
  function pad(n){ return (n<10?'0':'')+n; }
  /* แปลงข้อความวันที่ไทย → {start,end} · รองรับ "6 พ.ค. – 4 ก.ค. 2569", "18–19 ก.ค. 2569", "เสาร์ 20,27 มิ.ย. & 4,11 ก.ค. 2569" */
  window.parseThaiDateRange = function(str){
    var years=(String(str||'').match(/25\d\d/g)||[]), dates=[], re=/((?:\d{1,2}\s*[,–\-]\s*)*\d{1,2})\s*(ม\.ค\.|ก\.พ\.|มี\.ค\.|เม\.ย\.|พ\.ค\.|มิ\.ย\.|ก\.ค\.|ส\.ค\.|ก\.ย\.|ต\.ค\.|พ\.ย\.|ธ\.ค\.)(?:\s*(25\d\d))?/g, m;
    if(!years.length) return null;
    while((m=re.exec(str))){
      var y=(m[3]||years[years.length-1])-543, mo=MONTHS[m[2]];
      m[1].split(/[,–\-]/).forEach(function(d){ d=parseInt(d,10); if(d) dates.push(y+'-'+pad(mo)+'-'+pad(d)); });
    }
    if(!dates.length) return null;
    dates.sort();
    return {start:dates[0], end:dates[dates.length-1]};
  };
  /* วันนี้ (เวลาไทย) · ?today=YYYY-MM-DD ใช้จำลองวันสำหรับพรีวิว */
  window.suaccToday = function(){
    var q=new URLSearchParams(location.search).get('today');
    if(/^\d{4}-\d\d-\d\d$/.test(q||'')) return q;
    var d=new Date(Date.now()+7*3600e3);   /* UTC+7 */
    return d.getUTCFullYear()+'-'+pad(d.getUTCMonth()+1)+'-'+pad(d.getUTCDate());
  };
  window.eventRange = function(ev){
    if(ev.start && ev.end) return {start:ev.start, end:ev.end};
    return window.parseThaiDateRange(ev.date) || {start:'', end:'9999-12-31'};
  };
  /* 'ongoing' | 'upcoming' | 'past' */
  window.eventStatus = function(ev, today){
    var r=window.eventRange(ev); today=today||window.suaccToday();
    return r.end < today ? 'past' : (r.start > today ? 'upcoming' : 'ongoing');
  };
  /* แบ่งรายการ: current = กำลังจัด (จบเร็วสุดก่อน) แล้วตามด้วยที่ยังไม่เริ่ม (เริ่มเร็วสุดก่อน) · past = จบล่าสุดก่อน */
  window.splitByStatus = function(list){
    var t=window.suaccToday(), on=[], up=[], past=[];
    list.forEach(function(ev){ var s=window.eventStatus(ev,t); (s==='past'?past:s==='upcoming'?up:on).push(ev); });
    function by(k,dir){ return function(a,b){ var x=window.eventRange(a)[k], y=window.eventRange(b)[k]; return x<y?-dir:x>y?dir:0; }; }
    on.sort(by('end',1)); up.sort(by('start',1)); past.sort(by('end',-1));
    return {current:on.concat(up), past:past};
  };
})();
